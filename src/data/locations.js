import { slugify } from "@/lib/slug";

function loc(country, state, city, locality, lat, lng, currency) {
  return {
    country,
    state,
    city,
    citySlug: slugify(city),
    locality,
    localitySlug: slugify(locality),
    address: `${locality}, ${city}, ${state}`,
    lat,
    lng,
    currency,
  };
}

